const results = [] // { viewport, scenario, check, expected, actual, pass }
const consoleMessages = [] // { viewport, scenario, kind, text }
let ctx = { viewport: '-', scenario: '-' }

writeFileSync(
  LOG,
  `# TEAM-4181 — Phase 2 live browser verification log\n\n` +
    `Generated by \`qa/live.mjs\` against ${URL} (vite dev server), Playwright Chromium.\n` +
    `Real waits only — no fake timers. Undo window under test: ${UNDO_WINDOW_MS} ms.\n\n` +
    `| viewport | scenario | check | expected | actual | PASS/FAIL |\n` +
    `| --- | --- | --- | --- | --- | --- |\n`,
)

function cell(v) {
  if (v === undefined) return '_undefined_'
  if (v === null) return '_null_'
  let s = typeof v === 'string' ? v : JSON.stringify(v)
  s = s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ⏎ ')
  if (s.length > 300) s = s.slice(0, 297) + '...'
  if (s === '') return '_(empty string)_'
  return '`' + s + '`'
}

// Records a check. `pass` may be a boolean, or omitted for INFO-only rows.
function check(name, expected, actual, pass) {
  const verdict = pass === undefined ? 'INFO' : pass ? 'PASS' : 'FAIL'
  results.push({ ...ctx, check: name, expected, actual, verdict })
  appendFileSync(
    LOG,
    `| ${ctx.viewport} | ${ctx.scenario} | ${name} | ${cell(expected)} | ${cell(actual)} | ${verdict} |\n`,
  )
}

function eq(name, expected, actual) {
  const pass = JSON.stringify(expected) === JSON.stringify(actual)
  check(name, expected, actual, pass)
  return pass
}

function info(name, actual) {
  check(name, '(observation)', actual, undefined)
}

// ------------------------------------------------------------------- page prep

async function newPage(context) {
  const page = await context.newPage()
  page.on('console', (m) => {
    consoleMessages.push({ ...ctx, kind: `console.${m.type()}`, text: m.text() })
  })
  page.on('pageerror', (e) => {
    consoleMessages.push({ ...ctx, kind: 'pageerror', text: String(e && e.message ? e.message : e) })
  })
  await page.goto(URL, { waitUntil: 'load' })
  await page.waitForSelector('section.activity-feed')
  return page
}

const SEED_COUNT = 25

async function seed(page) {
  await page.evaluate(() => {
    localStorage.clear()
  })
  await page.evaluate(() => {
    const now = Date.now()
    const items = Array.from({ length: 25 }, (_, i) => ({
      id: 'qa-' + i,
      type: 'settings',
      description: 'QA seeded entry ' + i,
      timestamp: now - i * 60000,
    }))
    localStorage.setItem('demo.activity', JSON.stringify(items))
  })
  await page.reload({ waitUntil: 'load' })
  await page.waitForSelector('section.activity-feed')
}

async function clearStorage(page) {
  await page.evaluate(() => localStorage.clear())
  await page.reload({ waitUntil: 'load' })
  await page.waitForSelector('section.activity-feed')
}

