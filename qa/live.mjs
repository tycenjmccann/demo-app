  await page.screenshot({
    path: narrow ? `${DOCS}/TEAM-4162-narrow-clear.png` : `${DOCS}/TEAM-4162-clear.png`,
  })

  // ---- S2, still inside the window opened above
  ctx = { viewport: vp, scenario: 'S2 Undo' }
  const elapsed = Date.now() - tClear
  check(
    'Undo clicked while still inside the undo window',
    `< ${UNDO_WINDOW_MS} ms since Clear`,
    `${elapsed} ms`,
    elapsed < UNDO_WINDOW_MS,
  )
  await undoBtnOf(page).click()
  s = await snap(page)

  eq('20 li descriptions restored in identical order', before, s.descriptions)
  eq('stored entry count after Undo', SEED_COUNT, storedLen(s.raw))
  eq(
    'stored ids after Undo match seed order qa-0..qa-24',
    Array.from({ length: SEED_COUNT }, (_, i) => 'qa-' + i),
    storedIds(s.raw),
  )
  eq('status text after Undo', 'Activity restored.', s.statusText)
  eq('Undo button gone after Undo', false, s.undoPresent)
  eq('document.activeElement is the Clear activity button', true, s.activeIsClear)
  info('activeElement after Undo (tag/text)', `${s.activeTag} "${s.activeText}"`)

