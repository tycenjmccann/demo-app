  check(
    '.activity-feed__notice computed position is not fixed/absolute',
    'not fixed/absolute',
    s.noticePosition,
    s.noticePosition !== 'fixed' && s.noticePosition !== 'absolute',
  )
  eq("localStorage 'demo.activity' immediately after Clear", '[]', s.raw)
  eq('Clear activity button NOT present after Clear', false, s.clearPresent)
  eq('empty-state paragraph NOT present during undo window', false, s.emptyPresent)

