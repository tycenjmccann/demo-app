async function s9(page, vp, narrow) {
  ctx = { viewport: vp, scenario: 'S9 Visual' }
  await seed(page)
  let s = await snap(page)

  if (narrow) {
    check('scrollWidth <= 320 in default state', '<= 320', s.scrollWidth, s.scrollWidth <= 320)
  } else {
    info('scrollWidth in default state', s.scrollWidth)
  }

  // Clear button geometry at rest + rest colors.
  const clearGeom = await clearBtnOf(page).evaluate((el) => {
    const r = el.getBoundingClientRect()
    const cs = getComputedStyle(el)
    return { w: r.width, h: r.height, bg: cs.backgroundColor, color: cs.color }
  })
  check(
    'Clear button height ≈44px',
    '43–45 px',
    `${clearGeom.h.toFixed(2)} px`,
    clearGeom.h >= 43 && clearGeom.h <= 45,
  )
  check('Clear button width >= 24px', '>= 24 px', `${clearGeom.w.toFixed(2)} px`, clearGeom.w >= 24)
  eq('Clear button rest background', 'rgb(255, 255, 255)', clearGeom.bg)
  eq('Clear button rest color', 'rgb(71, 85, 105)', clearGeom.color)

  // Default-state screenshots FIRST, with the pointer parked away from the
  // button, so the evidence shows the rest style and not the hover style.
  await page.mouse.move(0, 0)
  await wait(120)
  if (narrow) await page.screenshot({ path: `${DOCS}/TEAM-4162-narrow.png` })
  else await page.screenshot({ path: `${DOCS}/TEAM-4162-default.png`, fullPage: true })

  // Hover colors.
  await clearBtnOf(page).hover()
  await wait(120)
  const hoverGeom = await clearBtnOf(page).evaluate((el) => {
    const cs = getComputedStyle(el)
    return { bg: cs.backgroundColor, color: cs.color }
  })
  eq('Clear button hover background', 'rgb(15, 23, 42)', hoverGeom.bg)
  eq('Clear button hover color', 'rgb(255, 255, 255)', hoverGeom.color)

  // Cleared state.
  await page.mouse.move(0, 0)
  await clearBtnOf(page).click()
  s = await snap(page)
  if (narrow) {
    check('scrollWidth <= 320 in cleared state', '<= 320', s.scrollWidth, s.scrollWidth <= 320)
  } else {
    info('scrollWidth in cleared state', s.scrollWidth)
  }
  const undoGeom = await undoBtnOf(page).evaluate((el) => {
    const r = el.getBoundingClientRect()
    const cs = getComputedStyle(el)
    return { w: r.width, h: r.height, bg: cs.backgroundColor, color: cs.color }
  })
  check(
    'Undo button height ≈44px',
    '43–45 px',
    `${undoGeom.h.toFixed(2)} px`,
    undoGeom.h >= 43 && undoGeom.h <= 45,
  )
  check('Undo button width >= 24px', '>= 24 px', `${undoGeom.w.toFixed(2)} px`, undoGeom.w >= 24)
  eq('Undo button rest background', 'rgb(255, 255, 255)', undoGeom.bg)
  eq('Undo button rest color', 'rgb(71, 85, 105)', undoGeom.color)
  await undoBtnOf(page).hover()
  await wait(120)
  const undoHover = await undoBtnOf(page).evaluate((el) => {
    const cs = getComputedStyle(el)
    return { bg: cs.backgroundColor, color: cs.color }
  })
  eq('Undo button hover background', 'rgb(15, 23, 42)', undoHover.bg)
  eq('Undo button hover color', 'rgb(255, 255, 255)', undoHover.color)

  // Restored state.
  await undoBtnOf(page).click()
  s = await snap(page)
  if (narrow) {
    check('scrollWidth <= 320 in restored state', '<= 320', s.scrollWidth, s.scrollWidth <= 320)
  } else {
    info('scrollWidth in restored state', s.scrollWidth)
  }
  await page.mouse.move(0, 0)
}

// ========================================================================= main

const browser = await chromium.launch()

for (const [w, h] of [
  [1280, 900],
  [320, 900],
]) {
  const vp = `${w}x${h}`
  const narrow = w === 320
  const context = await browser.newContext({ viewport: { width: w, height: h } })

  const scenarios = [
    ['S1+S2', s1s2],
    ['S3', s3],
    ['S4', s4],
    ['S5', s5],
    ['S6', s6],
    ['S7', s7],
    ['S8', s8],
    ['S9', s9],
  ]

  for (const [label, fn] of scenarios) {
    const page = await newPage(context)
    try {
      await fn(page, vp, narrow)
    } catch (err) {
      check(`${label} threw — scenario aborted`, 'no exception', String(err && err.message), false)
    } finally {
      await page.close()
    }
  }

  await context.close()
}

await browser.close()

