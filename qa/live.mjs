// One round-trip snapshot of everything the assertions need.
async function snap(page) {
  return page.evaluate(() => {
    const section = document.querySelector('section.activity-feed')
    const status = section ? section.querySelector('[role=status]') : null
    const heading = document.querySelector('#activity-feed-title')
    const notice = section ? section.querySelector('.activity-feed__notice') : null
    const btns = section ? Array.from(section.querySelectorAll('button')) : []
    const byName = (n) => btns.find((b) => (b.textContent || '').trim() === n) || null
    const clearBtn = byName('Clear activity')
    const undoBtn = byName('Undo')
    const empty = section ? section.querySelector('.activity-feed__empty') : null
    const ae = document.activeElement
    const box = (el) => {
      if (!el) return null
      const r = el.getBoundingClientRect()
      return { x: r.x, y: r.y, w: r.width, h: r.height }
    }
    return {
      liCount: section ? section.querySelectorAll('li').length : -1,
      ulCount: section ? section.querySelectorAll('ul').length : -1,
      roleListCount: section ? section.querySelectorAll('[role=list]').length : -1,
      descriptions: section
        ? Array.from(section.querySelectorAll('.activity-feed__description')).map((p) =>
            (p.textContent || '').trim(),
          )
        : [],
      statusPresent: !!status,
      statusCount: section ? section.querySelectorAll('[role=status]').length : -1,
      statusTag: status ? status.tagName : null,
      statusText: status ? (status.textContent || '').trim() : null,
      statusDisplay: status ? getComputedStyle(status).display : null,
      clearPresent: !!clearBtn,
      undoPresent: !!undoBtn,
      emptyPresent: !!empty,
      emptyText: empty ? (empty.textContent || '').trim() : null,
      noticePosition: notice ? getComputedStyle(notice).position : null,
      sectionBox: box(section),
      undoBox: box(undoBtn),
      clearBox: box(clearBtn),
      activeTag: ae ? ae.tagName : null,
      activeId: ae ? ae.id || null : null,
      activeText: ae ? (ae.textContent || '').trim().slice(0, 40) : null,
      activeIsUndo: !!undoBtn && ae === undoBtn,
      activeIsClear: !!clearBtn && ae === clearBtn,
      activeIsHeading: !!heading && ae === heading,
      scrollWidth: document.documentElement.scrollWidth,
      raw: localStorage.getItem('demo.activity'),
    }
  })
}

function storedIds(raw) {
  try {
    const v = JSON.parse(raw)
    return Array.isArray(v) ? v.map((e) => e.id) : null
  } catch {
    return null
  }
}

function storedLen(raw) {
  const ids = storedIds(raw)
  return ids === null ? null : ids.length
}

function boxInside(inner, outer) {
  if (!inner || !outer) return false
  return (
    inner.x >= outer.x - 0.5 &&
    inner.y >= outer.y - 0.5 &&
    inner.x + inner.w <= outer.x + outer.w + 0.5 &&
    inner.y + inner.h <= outer.y + outer.h + 0.5
  )
}

