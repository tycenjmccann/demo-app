async function s5(page, vp) {
  ctx = { viewport: vp, scenario: 'S5 New entry + 2nd clear merge' }
  await seed(page)
  const tClear1 = Date.now()
  await clearBtnOf(page).click()

  // New entry arrives while the window is open.
  await toggleOf(page).click()
  let s = await snap(page)
  const newEntry = s.descriptions[0] || null
  check(
    'new li appears with text containing "Turned email notifications"',
    'contains "Turned email notifications"',
    newEntry,
    typeof newEntry === 'string' && newEntry.includes('Turned email notifications'),
  )
  info('exact new entry description', newEntry)
  eq('li count after entry added during window', 1, s.liCount)
  eq('Clear activity button reappeared', true, s.clearPresent)
  eq('Undo still present after new entry', true, s.undoPresent)
  eq('storage has exactly 1 entry after toggle', 1, storedLen(s.raw))
  eq('status text unchanged during window', 'Activity cleared.', s.statusText)

  // F2b: does the second Clear produce any DOM mutation on [role=status]?
  await page.evaluate(() => {
    const status = document.querySelector('section.activity-feed [role=status]')
    window.__qaStatusMutations = 0
    window.__qaStatusTextBefore = (status.textContent || '').trim()
    window.__qaObserver = new MutationObserver((records) => {
      window.__qaStatusMutations += records.length
    })
    window.__qaObserver.observe(status, {
      childList: true,
      characterData: true,
      subtree: true,
      attributes: true,
    })
  })

  const tClear2 = Date.now()
  const sinceFirst = tClear2 - tClear1
  check(
    'second Clear happens while first window still open',
    `< ${UNDO_WINDOW_MS} ms since first Clear`,
    `${sinceFirst} ms`,
    sinceFirst < UNDO_WINDOW_MS,
  )
  await clearBtnOf(page).click()
  await wait(150) // let any mutation flush
  const mut = await page.evaluate(() => ({
    count: window.__qaStatusMutations,
    before: window.__qaStatusTextBefore,
    after: (document.querySelector('section.activity-feed [role=status]').textContent || '').trim(),
  }))
  s = await snap(page)
  eq('status text after second Clear', 'Activity cleared.', s.statusText)
  info('F2b — [role=status] MutationObserver record count across 2nd Clear', mut.count)
  info('F2b — status text before / after 2nd Clear', `${mut.before} / ${mut.after}`)
  check(
    'F2b — status text actually CHANGED on 2nd Clear (would re-announce)',
    'changed (>0 mutations)',
    `${mut.count} mutations, text identical: ${mut.before === mut.after}`,
    mut.count > 0,
  )
  eq('Undo present after second Clear', true, s.undoPresent)
  eq('storage emptied by second Clear', '[]', s.raw)

  const el2 = Date.now() - tClear2
  check('Undo clicked inside 2nd window', `< ${UNDO_WINDOW_MS} ms`, `${el2} ms`, el2 < UNDO_WINDOW_MS)
  await undoBtnOf(page).click()
  s = await snap(page)
  eq('storage has 26 entries after merged Undo (25 seeded + 1 toggle)', 26, storedLen(s.raw))
  eq('li count after merged Undo', 20, s.liCount)
  check(
    'toggle entry is first (newest) after merged Undo',
    'contains "Turned email notifications"',
    s.descriptions[0],
    typeof s.descriptions[0] === 'string' && s.descriptions[0].includes('Turned email notifications'),
  )
  eq('status text after merged Undo', 'Activity restored.', s.statusText)
}

async function s6(page, vp) {
  ctx = { viewport: vp, scenario: 'S6 Keyboard only' }
  await seed(page)
  await page.mouse.click(5, 5)

  // Tab until the Clear button owns focus.
  const focusSeq = []
  let tabs = 0
  let onClear = false
  for (let i = 0; i < 10; i++) {
    await page.keyboard.press('Tab')
    tabs++
    const d = await page.evaluate(() => {
      const ae = document.activeElement
      const clearBtn = Array.from(
        document.querySelectorAll('section.activity-feed button'),
      ).find((b) => (b.textContent || '').trim() === 'Clear activity')
      return {
        label: ae
          ? `${ae.tagName}${ae.id ? '#' + ae.id : ''}${
              ae.getAttribute && ae.getAttribute('aria-label')
                ? '[' + ae.getAttribute('aria-label') + ']'
                : ae.textContent
                ? '"' + (ae.textContent || '').trim().slice(0, 24) + '"'
                : ''
            }`
          : 'null',
        isClear: !!clearBtn && ae === clearBtn,
      }
    })
    focusSeq.push(d.label)
    if (d.isClear) {
      onClear = true
      break
    }
  }
  check('Clear activity reachable by Tab within 10 presses', true, onClear, onClear)
  info('number of Tab presses to reach Clear activity', tabs)
  info('focus sequence while tabbing', focusSeq.join(' → '))

  // Enter activates Clear, focus lands on Undo.
  await page.keyboard.press('Enter')
  let s = await snap(page)
  eq('Enter on Clear: Undo present', true, s.undoPresent)
  eq('Enter on Clear: activeElement === Undo button', true, s.activeIsUndo)
  info('activeElement after Enter on Clear', `${s.activeTag} "${s.activeText}"`)

  // Space activates Undo, focus returns to Clear.
  await page.keyboard.press('Space')
  s = await snap(page)
  eq('Space on Undo: entries restored (li count)', 20, s.liCount)
  eq('Space on Undo: activeElement === Clear button', true, s.activeIsClear)

  // Now the mirrored pair: Space on Clear, Enter on Undo.
  await page.keyboard.press('Space')
  s = await snap(page)
  eq('Space on Clear: Undo present', true, s.undoPresent)
  eq('Space on Clear: activeElement === Undo button', true, s.activeIsUndo)
  await page.keyboard.press('Enter')
  s = await snap(page)
  eq('Enter on Undo: entries restored (li count)', 20, s.liCount)
  eq('Enter on Undo: activeElement === Clear button', true, s.activeIsClear)

  // Expiry with focus parked on Undo → focus must land on the heading.
  await page.keyboard.press('Space') // clear again via keyboard
  s = await snap(page)
  eq('pre-expiry: focus parked on Undo', true, s.activeIsUndo)
  await wait(5200)
  s = await snap(page)
  eq('after expiry: activeElement is #activity-feed-title', true, s.activeIsHeading)
  check(
    'after expiry: focus was NOT dropped to body',
    'not BODY',
    `${s.activeTag}${s.activeId ? '#' + s.activeId : ''}`,
    s.activeTag !== 'BODY',
  )
  info('activeElement tagName#id after expiry', `${s.activeTag}${s.activeId ? '#' + s.activeId : ''}`)
}

